#!/usr/bin/env bash
set -euo pipefail
script=$(realpath "$0")
cd "$(dirname "$script")/../ops"
node=${LOOM_INSTANCE:-/loom/ops/dev-build}
project=${LOOM_PROJECT:-loom-dev-build}
if [[ ! -r "$node/compose.env" ]]; then
  if [[ $EUID -eq 0 ]]; then echo "Missing instance configuration: $node/compose.env" >&2; exit 1; fi
  exec sudo -n env LOOM_INSTANCE="$node" LOOM_PROJECT="$project" LOOM_BUILD_ENV="${LOOM_BUILD_ENV:-$node/build.env}" bash "$script" "$@"
fi
engine=(docker)
if ! docker info >/dev/null 2>&1; then engine=(sudo -n docker); fi
args=("${engine[@]}" compose -p "$project"
  --env-file "$node/compose.env" --env-file "$node/network.env"
  -f compose.loom.yaml)
# Research images and scripts are Job profile resources, not core Compose overlays.
if [[ -f "$node/executor.env" ]]; then args+=(--env-file "$node/executor.env" -f compose.executor.yaml); fi
if [[ -f "$node/observations.env" ]]; then args+=(--env-file "$node/observations.env" -f compose.observations.yaml); fi
build_env=${LOOM_BUILD_ENV:-$node/build.env}
if [[ -f "$build_env" ]]; then args+=(--env-file "$build_env"); fi
if [[ -f "$node/data.env" ]]; then args+=(--env-file "$node/data.env" -f compose.data.yaml); fi
if [[ -f "$node/compose-storage.yaml" ]]; then args+=(-f "$node/compose-storage.yaml"); fi
if [[ -f "$node/secrets/fence-token" && -f "$node/secrets/fence-ca.pem" ]]; then
  args+=(-f compose.loom.fence.yaml)
fi
if [[ -f "$node/development" ]]; then args+=(-f compose.dev.yaml); fi
if [[ -f "$node/compose-network.yaml" ]]; then args+=(-f "$node/compose-network.yaml"); fi
if [[ -f "$node/compose-tailnet.yaml" ]]; then args+=(-f "$node/compose-tailnet.yaml"); fi
if [[ -f "$node/compose-admission.yaml" ]]; then args+=(-f "$node/compose-admission.yaml"); fi
if [[ -f "$node/release-check.env" ]]; then args+=(--env-file "$node/release-check.env"); fi
# Machine-owned overrides always win, and are never generated by releases.
if [[ -f "$node/override.env" ]]; then args+=(--env-file "$node/override.env"); fi
if [[ -f "$node/compose.override.yaml" ]]; then args+=(-f "$node/compose.override.yaml"); fi
exec "${args[@]}" "$@"
