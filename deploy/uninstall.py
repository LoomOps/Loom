"""Uninstall one Loom stack and its managed Sharing state; never run from Dashboard."""
import argparse
import fcntl
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import sqlite3
import sys
from urllib.parse import quote, urlsplit

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'dashboard'))
from admission import TailnetAPI, RemoteError, group_name, validate
from tailnet import env_values, expected_routes, write
import update


def load(root):
    root=Path(root)
    if not root.is_absolute() or any(p.is_symlink() for p in [root,*root.parents]):
        raise ValueError('Use an absolute, non-symlink instance directory')
    c=validate(json.loads((root/'secrets/admission/config.json').read_text()))
    if c.get('enrollment_mode','sharing')!='sharing':raise ValueError('Sharing configuration required')
    # Runtime config contains container paths: only use the known host paths.
    c={**c,'database':str(root/'admission/requests.sqlite3'),
       'credential_file':str(root/'secrets/admission/management.json')}
    return root,c


def sql(path):
    return sqlite3.connect('file:'+str(path)+'?mode=ro',uri=True,timeout=15)


def records(root,c):
    path=Path(c['database'])
    if not path.is_file():raise ValueError('Access records missing; cannot infer owned invitations')
    with sql(path) as db:
        db.row_factory=sqlite3.Row
        rows=[dict(r) for r in db.execute('SELECT * FROM share_requests')]
    if any(r['machine']!=c['machine_id'] for r in rows):raise ValueError('Access DB is shared with another machine')
    return rows


def clean_policy(policy,c):
    """Remove only the installation-specific group and grants; preserve native admin."""
    p=json.loads(json.dumps(policy));group=group_name(c['machine_id'],c['device_id'])
    for users in p.get('groups',{}).values():
        if group in users:raise ValueError('Managed access group is referenced by another group')
    for section in ('acls','ssh'):
        if group in json.dumps(p.get(section,[])):raise ValueError('Managed group has non-Loom policy references')
    grants=[]
    for grant in p.get('grants',[]):
        if group not in grant.get('src',[]):grants.append(grant);continue
        if grant.get('src')!=[group] or set(grant.get('dst',[]))!=set(c['addresses']) or not set(grant.get('ip',[])).issubset({'tcp:'+str(x) for x in c['ports']}) or set(grant)-{'src','dst','ip'}:
            raise ValueError('Managed group grant has been extended; reconcile before uninstall')
    # Remove the exact public gateway exception generated by access_setup.
    public=urlsplit(c['origin']).port or 443
    grants=[g for g in grants if not (set(g.get('src',[]))=={'autogroup:member','autogroup:shared'} and set(g.get('dst',[]))==set(c['addresses']) and g.get('ip')==['tcp:'+str(public)] and set(g)=={'src','dst','ip'})]
    p['grants']=grants;p.get('groups',{}).pop(group,None)
    return p


def listeners(root,c,state):
    """Whole listeners are removed only if every handler belongs to this instance."""
    private=urlsplit(c['dashboard_origin']);public=urlsplit(c['origin'])
    origins=[(urlsplit('https://'+private.hostname+':'+str(port)),expected_routes(root),False) for port in c['ports']]
    origins.append((public,{'/':'http://127.0.0.1:'+str(c['host_port'])},True))
    result=[]
    if (private.port or 443) not in c['ports'] or (public.port or 443) in c['ports']:
        raise ValueError('Inconsistent public/private listener ownership')
    for origin,expected,funnel in origins:
        host=origin.hostname+':'+str(origin.port or 443)
        actual=state.get('Web',{}).get(host,{}).get('Handlers',{})
        if any(path not in expected or item!={'Proxy':expected[path]} for path,item in actual.items()):
            raise ValueError('Serve listener contains unrelated or replaced routes: '+host)
        if actual:result.append({'port':origin.port or 443,'funnel':funnel,'host':host})
    return result


def inspect(root,project,api=None,run=update.run):
    root,c=load(root)
    if not re.fullmatch(r'[a-z0-9][a-z0-9_-]*',project):raise ValueError('Invalid Compose project')
    api=api or TailnetAPI(c['credential_file'])
    device,_=api.call('GET','/device/'+quote(c['device_id'],safe=''))
    if not set(c['addresses']).issubset(device.get('addresses',[])):raise ValueError('Machine identity changed')
    rows=records(root,c)
    invites,_=api.call('GET','/device/'+quote(c['device_id'],safe='')+'/device-invites')
    invites=invites.get('invites',[]) if isinstance(invites,dict) else invites
    if not isinstance(invites,list):raise ValueError('Invalid sharing inventory')
    # An unconfirmed invitation cannot be forgotten; an operator must reconcile it.
    if any(r['send_started'] and not r['invite_id'] for r in rows):
        raise ValueError('Unconfirmed invitation delivery; reconcile its ID before uninstall')
    owned={str(r['invite_id']) for r in rows if r['invite_id']}
    available={str(i['id']) for i in invites}
    policy,_=api.call('GET','/tailnet/'+quote(c['tailnet'],safe='')+'/acl');clean_policy(policy,c)
    serve=json.loads(run('tailscale','serve','status','--json'))
    ports=listeners(root,c,serve)
    # Reject wrong project/instance selection before stopping any service.
    all_ids=run('docker','ps','-aq','--filter','label=com.docker.compose.service=loom-ops').split()
    for item in json.loads(run('docker','inspect',*all_ids)) if all_ids else []:
        if any(m.get('Source')==str(root/'runtime') and m.get('Destination')=='/loom/ops' for m in item.get('Mounts',[])) and item['Config']['Labels'].get('com.docker.compose.project')!=project:
            raise ValueError('Instance is running under a different Compose project')
    ids=run('docker','ps','-aq','--filter','label=com.docker.compose.project='+project).split()
    containers=json.loads(run('docker','inspect',*ids)) if ids else []
    for item in containers:
        if not any(m.get('Source')==str(root/'runtime') and m.get('Destination')=='/loom/ops' for m in item.get('Mounts',[])) and item['Config']['Labels'].get('com.docker.compose.service')=='loom-ops':
            raise ValueError('Compose project belongs to another instance')
    unit=Path('/etc/systemd/system')/(project+'-stack.service')
    if unit.exists():
        text=unit.read_text()
        if 'LOOM_INSTANCE='+str(root)+' ' not in text or 'LOOM_PROJECT='+project+'\n' not in text:
            raise ValueError('Startup unit belongs to another instance')
    identity={'instance':str(root),'project':project,'machine':c['machine_id'],'device':c['device_id'],'addresses':c['addresses'],'ports':c['ports'],'origin':c['origin'],'dashboard_origin':c['dashboard_origin']}
    return {'schema':'loom-uninstall/v1','instance':str(root),'project':project,'identity':identity,
            'fingerprint':hashlib.sha256(json.dumps(identity,sort_keys=True).encode()).hexdigest(),
            'requests':len(rows),'invites':sorted(owned & available),'unmanaged_shares_preserved':len(available-owned),
            'listeners':ports,'startup_unit':str(unit) if unit.exists() else None,
            'preserved':['Tailscale login/device/tags and native Admin policy','unrelated policies, shares and listeners','Jobs, artifacts, storage mounts, components, profiles','shared helpers, images, dependencies and service account','external backups and user-side client settings']}


def cleanup_policy(api,c):
    path='/tailnet/'+quote(c['tailnet'],safe='')+'/acl'
    for _ in range(3):
        old,headers=api.call('GET',path);new=clean_policy(old,c)
        if old==new:return
        etag=next((v for k,v in headers.items() if k.lower()=='etag'),None)
        if not etag:raise ValueError('Policy ETag required')
        result,_=api.call('POST',path+'/validate',new)
        if result.get('errors') or result.get('message'):raise ValueError('Policy validation failed')
        try:api.call('POST',path,new,{'If-Match':etag})
        except RemoteError as e:
            if e.status==412:continue
            raise
        return
    raise ValueError('Policy changed concurrently; resume after reviewing it')


def purge(root):
    # Fixed paths only. Never recurse over /loom or a storage directory.
    directories=['admission','dashboard-auth','secrets/admission','secrets/sso','network-backups']
    files=['compose-admission.yaml','compose-tailnet.yaml','config/tailnet-plan.json','config/access-plan.json','config/serve-before.json']
    for rel in directories+files:
        path=root/rel
        if path.is_symlink():raise ValueError('Refusing symlink cleanup: '+rel)
    api_path=root/'config/api.json';api=json.loads(api_path.read_text())
    api.pop('tailscale_auth',None);api.pop('dashboard_auth',None)
    st=api_path.stat();write(api_path,api,st.st_uid,st.st_gid)
    env_path=root/'network.env';env=env_values(env_path)
    env.pop('LOOM_TAILSCALE_TRUSTED_PROXIES',None);env['LOOM_DEV_NO_AUTH']='0'
    st=env_path.stat();write(env_path,''.join(f'{k}={v}\n' for k,v in env.items()),st.st_uid,st.st_gid)
    for rel in directories:
        path=root/rel
        if path.exists():shutil.rmtree(path)
    for rel in files:(root/rel).unlink(missing_ok=True)


def _apply_locked(plan,confirmation,receipt,api=None,run=update.run):
    root=Path(plan['instance']);receipt=Path(receipt)
    if confirmation!=plan['identity']['machine']:raise ValueError('Confirm the installation machine ID from the plan')
    if receipt.is_symlink() or not receipt.is_absolute() or receipt.is_relative_to(root):raise ValueError('Receipt must be outside the instance')
    previous=json.loads(receipt.read_text()) if receipt.exists() else None
    if previous and previous.get('fingerprint')!=plan['fingerprint']:raise ValueError('Receipt belongs to another plan')
    if previous and previous.get('state')=='complete':return previous
    if previous and previous.get('stage')=='remote_clean':
        purge(root);previous.update(state='complete');write(receipt,previous);return previous
    root,c=load(root);api=api or TailnetAPI(c['credential_file'])
    current=inspect(root,plan['project'],api,run)
    if current['fingerprint']!=plan['fingerprint']:raise ValueError('Installed identity/configuration changed')
    if set(current['invites'])-set(plan['invites']) or current['requests']>plan['requests']:raise ValueError('New access requests/shares appeared; create a fresh plan')
    owned={str(r['invite_id']) for r in records(root,c) if r['invite_id']}
    if not set(plan['invites']).issubset(owned):raise ValueError('Plan contains an unmanaged invitation')
    receipt.parent.mkdir(parents=True,exist_ok=True)
    with (receipt.parent/(receipt.name+'.lock')).open('a') as lock:
        fcntl.flock(lock,fcntl.LOCK_EX|fcntl.LOCK_NB)
        record=previous or {'schema':'loom-uninstall-receipt/v1','fingerprint':plan['fingerprint'],'instance':str(root),'state':'running','stage':'preflight'}
        db=root/'runtime/ops.sqlite3'
        if not previous:
            resources_returned(root)
            update.idle_gate(db)
        try:
            write(receipt,record)
            if current['startup_unit']:run('systemctl','disable','--now',Path(current['startup_unit']).name)
            # No resource-return shortcut, no --volumes, no image/data pruning.
            update.compose(ROOT,root,plan['project'],'stop')
            if run('docker','ps','-q','--filter','label=com.docker.compose.project='+plan['project']):
                raise ValueError('Compose services have not stopped')
            if current['startup_unit']:
                Path(current['startup_unit']).unlink();run('systemctl','daemon-reload')
            # Worker is stopped; no new invitations can race the cleanup.
            record.update(stage='stopped');write(receipt,record)
            stopped=inspect(root,plan['project'],api,run)
            if set(stopped['invites'])-set(plan['invites']) or stopped['requests']>plan['requests']:
                raise ValueError('Access state changed while stopping; review a fresh plan before resume')
            cleanup_policy(api,c)
            for invite in plan['invites']:
                try:api.call('DELETE','/device-invites/'+quote(invite,safe=''))
                except RemoteError as e:
                    if e.status!=404:raise
            remaining,_=api.call('GET','/device/'+quote(c['device_id'],safe='')+'/device-invites')
            remaining=remaining.get('invites',[]) if isinstance(remaining,dict) else remaining
            if set(plan['invites']) & {str(i['id']) for i in remaining}:raise ValueError('Sharing removal not yet confirmed')
            policy,_=api.call('GET','/tailnet/'+quote(c['tailnet'],safe='')+'/acl')
            if clean_policy(policy,c)!=policy:raise ValueError('Policy removal not confirmed')
            for item in current['listeners']:
                run('tailscale','funnel' if item['funnel'] else 'serve','--https='+str(item['port']),'--yes','off')
            after=json.loads(run('tailscale','serve','status','--json'))
            if any(after.get('Web',{}).get(x['host'],{}).get('Handlers') for x in current['listeners']):raise ValueError('Listener removal not confirmed')
            update.compose(ROOT,root,plan['project'],'down')
            record.update(stage='remote_clean');write(receipt,record)
            purge(root);record.update(state='complete');write(receipt,record)
            return record
        except BaseException:
            record['state']='incomplete';write(receipt,record)
            # Remain stopped/fenced. Keep management credentials and local records
            # until remote cleanup is confirmed; resume with the same plan/receipt.
            raise



def resources_returned(root):
    env=root/'executor.env'
    if not env.exists():return
    host=Path(env_values(env)['LOOM_EXECUTOR_HOST'])
    settings=json.loads((host/'config.json').read_text())
    token=(root/'secrets/executor-token').read_text().strip()
    digest=hashlib.sha256(token.encode()).hexdigest()
    ids=[name for name,c in settings['instances'].items() if c.get('token_sha256')==digest]
    if len(ids)!=1:raise ValueError('Executor installation identity is ambiguous')
    with sql(host/'executor.sqlite3') as db:
        if db.execute("SELECT 1 FROM tickets WHERE instance=? AND state!='returned' LIMIT 1",(ids[0],)).fetchone():
            raise ValueError('Executor resources have not returned')


def apply(plan,confirmation,receipt,api=None,run=update.run):
    root=Path(plan['instance'])
    if not root.is_absolute() or any(p.is_symlink() for p in [root,*root.parents]):
        raise ValueError('Use an absolute, non-symlink instance directory')
    lockpath=root/'.uninstall.lock'
    if lockpath.is_symlink():raise ValueError('Invalid uninstall lock')
    with lockpath.open('a') as lock:
        fcntl.flock(lock,fcntl.LOCK_EX|fcntl.LOCK_NB)
        return _apply_locked(plan,confirmation,receipt,api,run)


def main():
    p=argparse.ArgumentParser(description=__doc__);sub=p.add_subparsers(dest='action',required=True)
    a=sub.add_parser('plan');a.add_argument('--instance',type=Path,required=True);a.add_argument('--project',required=True);a.add_argument('--output',type=Path,required=True)
    a=sub.add_parser('apply');a.add_argument('--plan',type=Path,required=True);a.add_argument('--confirm-machine',required=True);a.add_argument('--receipt',type=Path,required=True)
    a=p.parse_args()
    if a.action=='plan':
        value=inspect(a.instance,a.project);write(a.output,value);print(json.dumps(value,indent=2))
    else:print(json.dumps(apply(json.loads(a.plan.read_text()),a.confirm_machine,a.receipt),indent=2))

if __name__=='__main__':main()
